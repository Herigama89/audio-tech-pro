"""
The Analog Console's pictures: the knob (your uploaded red-capped knob, 31 frames) painted in each section's colour,
and the master's VU face (our own, vu_meter.py) without its needle (the console draws it).

    python3 make_console_assets.py      -> Resources/effects/ac_knob_<colour>.png, ac_vu.png and Source/ui/AnalogConsoleArt.h
"""
import os, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname (os.path.abspath (__file__))
ROOT = os.path.join (HERE, "..", "..")
OUT = os.path.join (ROOT, "Resources", "effects")
sys.path.insert (0, os.path.join (ROOT, "Tools", "compressor_skins"))
import vu_meter

COLOURS = { "grey": (150, 156, 164), "white": (226, 226, 231), "green": (46, 190, 110), "red": (214, 40, 36),
            "emerald": (40, 170, 95), "blue": (60, 110, 230), "brown": (150, 100, 52), "gold": (214, 170, 40) }
FRAME = 64

def knobs():
    src = Image.open (os.path.join (HERE, "knob_source.png")).convert ("RGBA")
    n = src.height // src.width
    frames = [src.crop ((0, k * src.width, src.width, (k + 1) * src.width)).resize ((FRAME, FRAME), Image.LANCZOS) for k in range (n)]
    strip = Image.new ("RGBA", (FRAME, FRAME * n))
    for k, f in enumerate (frames):
        strip.paste (f, (0, k * FRAME))
    im = np.asarray (strip).astype (np.float32) / 255
    r, g, b = im[..., 0], im[..., 1], im[..., 2]
    mx, mn = im[..., :3].max (-1), im[..., :3].min (-1)
    sat = (mx - mn) / (mx + 1e-6)
    red = np.clip ((sat - 0.25) / 0.25, 0, 1) * (r > g * 1.3)
    shade = r / (np.percentile (r[red > 0.5], 90) + 1e-6)
    for name, c in COLOURS.items():
        out = im.copy()
        col = np.array (c, np.float32) / 255
        for i in range (3):
            out[..., i] = im[..., i] * (1 - red) + np.clip (col[i] * shade, 0, 1) * red
        Image.fromarray ((out * 255).astype (np.uint8), "RGBA").save (os.path.join (OUT, "ac_knob_%s.png" % name), optimize = True)
    return n

def vu():
    info = {}
    w, h = 380, 200
    vu_meter.vu (w, h, 0.0, face = "cream", needle = False, info = info).save (os.path.join (OUT, "ac_vu.png"), optimize = True)
    mask = info["hood"]; box = mask.getbbox()
    face = Image.open (os.path.join (OUT, "ac_vu.png")).convert ("RGBA")
    hood = face.crop (box); hood.putalpha (mask.crop (box)); hood.save (os.path.join (OUT, "ac_vu_hood.png"), optimize = True)
    return w, h, info, box

def main():
    frames = knobs()
    w, h, info, box = vu()
    x0, y0, ww, wh = info["window"]
    L = ["#pragma once", "// Generated by Tools/console_assets/make_console_assets.py", "namespace riff::analogart", "{",
         "    inline constexpr int knobFrames = %d, knobFrame = %d;" % (frames, FRAME),
         "    // the master VU (%d x %d): the needle's pivot, reach, the thick part, widths, the window, the swing (degrees each side)" % (w, h),
         "    inline constexpr float vuWidth = %d, vuHeight = %d;" % (w, h),
         "    inline constexpr float vuPivotX = %.2ff, vuPivotY = %.2ff, vuReach = %.2ff, vuThickTo = %.2ff, vuThin = %.2ff, vuThick = %.2ff;"
             % (info["pivot"][0], info["pivot"][1], info["reach"], info["thickTo"], info["thin"], info["thick"]),
         "    inline constexpr float vuWindow[4] { %.1ff, %.1ff, %.1ff, %.1ff };" % (x0, y0, ww, wh),
         "    inline constexpr float vuHood[4] { %.1ff, %.1ff, %.1ff, %.1ff };" % (box[0], box[1], box[2] - box[0], box[3] - box[1]),
         "    inline constexpr float vuSwing = %.1ff;" % info["swing"], "}", ""]
    open (os.path.join (ROOT, "Source", "ui", "AnalogConsoleArt.h"), "w").write ("\n".join (L))
    print ("done", frames)

if __name__ == "__main__":
    main()
